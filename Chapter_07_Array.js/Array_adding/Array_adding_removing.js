let arr =[1,2,3];
console.log(arr);

//Add to end
arr.push(4);
console.log(arr);

//Remove from END

arr.pop();
console.log(arr);

arr.push(5,6);
console.log(arr);

//Add to the beginning
arr.unshift(0)
console.log(arr);

arr.shift()
console.log(arr);

arr.splice(2,1)
console.log(arr);

arr.splice(2,0,99)
console.log(arr);

arr.splice(1,1,10,20);
console.log(arr);